const { Router } = require('express');
const expressfileUpload = require('express-fileupload');
const { validarJWT } = require('../middlewares/validators/validar-jwt');
const { authorizeProviderAccess } = require('../middlewares/authorize-provider-access');
const controller = require('../controllers/provider-company.controller');
const router = Router();
router.get('/', [validarJWT, authorizeProviderAccess('view')], controller.list);
router.get('/:id', [validarJWT, authorizeProviderAccess('view')], controller.get);
router.get('/:id/printable-profile', [validarJWT, authorizeProviderAccess('view')], controller.printableProfile);
router.post('/', [validarJWT, authorizeProviderAccess('create')], controller.create);
router.put('/:id', [validarJWT, authorizeProviderAccess('update')], controller.update);
router.post('/:id/documents/:type', [validarJWT, authorizeProviderAccess('update'), expressfileUpload({ limits: { fileSize: 8 * 1024 * 1024 }, abortOnLimit: true })], controller.uploadDocument);
router.put('/:id/providers', [validarJWT, authorizeProviderAccess('update')], controller.setProviders);
router.post('/:id/sites', [validarJWT, authorizeProviderAccess('create')], controller.createSite);
router.put('/:id/sites/:providerId', [validarJWT, authorizeProviderAccess('update')], controller.updateSite);
router.put('/:id/sites/:providerId/headquarters', [validarJWT, authorizeProviderAccess('update')], controller.transferHeadquarters);
router.get('/:id/sites/:providerId/pending', [validarJWT, authorizeProviderAccess('view')], controller.pendingSummary);
router.put('/:id/sites/:providerId/deactivate', [validarJWT, authorizeProviderAccess('delete')], controller.deactivateSite);
router.put('/:id/sites/:providerId/contacts', [validarJWT, authorizeProviderAccess('update')], controller.replaceCollection('contacts'));
router.put('/:id/sites/:providerId/materials', [validarJWT, authorizeProviderAccess('update')], controller.replaceCollection('materials'));
router.put('/:id/sites/:providerId/bank-accounts', [validarJWT, authorizeProviderAccess('update')], controller.replaceCollection('bankAccounts'));
module.exports = router;
